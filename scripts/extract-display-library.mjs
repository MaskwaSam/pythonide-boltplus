// Reproduce the complete named catalogue from the supplied, preserved app.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = fileURLToPath(new URL('../', import.meta.url));
const archive = root + 'sphero-boltplus-ev3-file-resource-20260927.zip';
const bundle = execFileSync('python3', ['-c', 'import sys,zipfile; sys.stdout.buffer.write(zipfile.ZipFile(sys.argv[1]).read("static/js/main.55f08aa7.js"))', archive], { maxBuffer: 20000000 }).toString();
const arrays = [];
for (const match of bundle.matchAll(/JSON\.parse\(('(?:\\.|[^'\\])*')\)/g)) {
  // The regex permits a string literal only, never arbitrary bundle code.
  const value = vm.runInNewContext(`JSON.parse(${match[1]})`, {}, { timeout: 1000 });
  if (Array.isArray(value) && value.length && value.every(item => item && typeof item === 'object')) arrays.push(value);
}
const records = new Map();
const categories = new Map();
for (const array of arrays) for (const item of array) {
  if (typeof item.id === 'string' && Array.isArray(item.all) && item.icon_png) categories.set(item.id, item);
  if (typeof item.id !== 'string' || typeof item.fwid !== 'string' || !item.paths?.thumbnail_png) continue;
  const old = records.get(item.id);
  if (old && old.fwid !== item.fwid) throw new Error(`Conflicting firmware IDs: ${item.id}`);
  records.set(item.id, item);
}
const catalogue = { source: {
  archive: archive.split('/').at(-1),
  archiveSha256: createHash('sha256').update(readFileSync(archive)).digest('hex'),
  bundle: 'static/js/main.55f08aa7.js',
  bundleSha256: createHash('sha256').update(bundle).digest('hex'),
  note: 'Named assets from the supplied Sphero Edu enums; robot firmware contains the display data.'
} };
const thumbnails = [];
for (const [kind, enumName] of [['images', 'DisplayImage'], ['animations', 'DisplayAnimation']]) {
  const anchor = `e.${enumName}=Object.freeze(`, start = bundle.indexOf(anchor) + anchor.length;
  if (start < anchor.length) throw new Error(`Missing ${enumName}`);
  const end = bundle.indexOf('})', start) + 1;
  const literal = bundle.slice(start, end);
  // The enum is a simple object of identifier:string pairs; no executable values.
  if (!/^\{(?:[A-Za-z0-9_]+:"[a-z0-9-]+",?)+\}$/.test(literal)) throw new Error('Unexpected enum format');
  const values = vm.runInNewContext(`(${literal})`, {}, { timeout: 1000 });
  catalogue[kind] = Object.entries(values).map(([enumName, id]) => {
    let item = records.get(id);
    if (!item && id.startsWith('random-')) {
      const category = [...categories.values()].find(category => category.all.includes(id));
      if (!category) throw new Error(`Missing random category: ${id}`);
      item = { id, fwid: null, name: { en: `Random ${category.name.en}` }, canvas: true,
        choices: category.all.filter(choice => choice !== id && records.has(choice)),
        paths: {}, category: category.id };
      if (!item.choices.length) throw new Error(`Empty random category: ${id}`);
      item.paths.thumbnail_png = records.get(item.choices[0]).paths.thumbnail_png;
    }
    if (!item) throw new Error(`Missing metadata: ${id}`);
    const thumbnail = 'display_assets/' + item.paths.thumbnail_png;
    thumbnails.push(thumbnail);
    let constant = id.replaceAll('-', '_').toUpperCase();
    if (/^[0-9]/.test(constant)) constant = enumName.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase();
    return { id, fwid: item.fwid === null ? null : Number(item.fwid), constant, enumName,
      name: item.name.en, category: item.category || (kind === 'images' ? item.paths.thumbnail_png.split('/')[1] : 'animations'),
      thumbnail, canvas: item.canvas === true, ...(item.choices ? { choices: item.choices } : {}) };
  });
  if (new Set(catalogue[kind].map(item => item.constant)).size !== catalogue[kind].length) throw new Error('Duplicate Python constant');
}
writeFileSync(root + 'display-library.js', '// Generated by scripts/extract-display-library.mjs from the supplied Sphero app.\nwindow.BoltDisplayLibrary = ' + JSON.stringify(catalogue) + ';\n');
// Only the selected thumbnail paths may be extracted; preserve original archive.
execFileSync('python3', ['-c', 'import json,pathlib,sys,zipfile; root=pathlib.Path(sys.argv[2]); z=zipfile.ZipFile(sys.argv[1]); paths=json.load(sys.stdin); assert all(p.startswith("display_assets/") and ".." not in pathlib.PurePosixPath(p).parts for p in paths); [(root/p).parent.mkdir(parents=True,exist_ok=True) or (root/p).write_bytes(z.read(p)) for p in paths]', archive, root], { input: JSON.stringify([...new Set(thumbnails)]) });
writeFileSync(root + 'display-library-manifest.json', JSON.stringify({ ...catalogue.source,
  images: catalogue.images.length, animations: catalogue.animations.length,
  concreteImages: catalogue.images.filter(item => item.fwid !== null).length,
  concreteAnimations: catalogue.animations.filter(item => item.fwid !== null).length,
  emojiImages: catalogue.images.filter(item => item.category === 'emoji' && item.fwid !== null).length,
  thumbnails: thumbnails.map(path => ({ path, sha256: createHash('sha256').update(readFileSync(root + path)).digest('hex') }))
}, null, 2) + '\n');
console.log(JSON.stringify({ images: catalogue.images.length, animations: catalogue.animations.length,
  emoji: catalogue.images.filter(item => item.category === 'emoji' && item.fwid !== null).length, thumbnails: new Set(thumbnails).size }));
